h = {"сагсан бөмбөг", "хөлбөмбөг", "бейсбол", "волейбол"}
o = {"волейбол", "гимнастик", "сагсан бөмбөг", "бүжиг"}

# Ангийн хөвгүүд ба охид өөр өөр спортоор хичээллэдэг
print("Хөвгүүдийн спорт:", h)
print("Охидын спорт:", o)

# Хоёулаа нийтлэг спорт юу вэ?
print("Хоёулаа нийтлэг:", h & o)

# Зөвхөн охидын сонгосон спорт юу вэ?
print("Зөвхөн охидын сонгосон:", o - h)

# Нийт спортын төрөл хэд вэ?
niit = h | o
print("Нийт спортын төрөл:", len(niit))