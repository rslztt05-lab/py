h1 = {"алим", "банана", "усан үзэм", "жүрж"}
h2 = {"банана", "лийр", "жүрж", "нэрс"}

# Хоёр хүний дуртай жимсний жагсаалт
print("1 :", h1)
print("2 :", h2)

# Хоёуланд нь таалагддаг жимс
print("Хоёуланд нь таалагддаг:", h1 & h2)

# Нэгэнд нь байгаа, нөгөөд байхгүй жимс
print("1 :", h1 - h2)
print("З :", h2 - h1)
print("Нэгэнд нь л байгаа:", h1 ^ h2)

# Бүх жимсний жагсаалт
print("Buh :", h1 | h2)